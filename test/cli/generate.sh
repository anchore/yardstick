#!/usr/bin/env bash
# Extracts the vunnel records each CLI test scenario builds its DB from, with grype's own fixture
# tool (internal/dbtest/cmd/manager) at a pinned grype tag. Nothing under testdata/<scenario>/vunnel
# is written by hand; this script is the only way to change it. The records are the pin: the
# vunnel workspaces move daily, so a regeneration is a deliberate change to every scenario.
set -euo pipefail

GRYPE_TAG=v0.120.1
GRYPE_REPO=${GRYPE_REPO:-https://github.com/anchore/grype}
VUNNEL_DATA=${VUNNEL_DATA:-$HOME/code/grype-db/data/vunnel}

here=$(cd "$(dirname "$0")" && pwd)
out=$here/testdata
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

git -c advice.detachedHead=false clone -q --depth 1 --branch "$GRYPE_TAG" "$GRYPE_REPO" "$work/grype"
(cd "$work/grype" && go build -o "$work/manager" ./internal/dbtest/cmd/manager)

provenance=()

# extract <scenario> <provider> <select>...: the provider's records whose id contains a select.
# The manager matches with SQL LIKE '%<select>%', so a select that is a prefix of another id would
# pull that record too; the count check catches it.
extract() {
	local scenario=$1 provider=$2
	shift 2
	local dir=$out/$scenario/vunnel mode=--output args=()
	[[ -d $dir ]] && mode=--append
	for s in "$@"; do args+=(--select "$s"); done
	"$work/manager" extract --vunnel-data "$VUNNEL_DATA" --provider "$provider" "${args[@]}" "$mode" "$dir" >/dev/null
	local n
	n=$(find "$dir/$provider/results" -name '*.json' | wc -l | tr -d ' ')
	if [[ $n != "$#" ]]; then
		echo "$scenario/$provider: $# selects matched $n records" >&2
		exit 1
	fi
	provenance+=("$scenario $provider ($(jq -r .timestamp "$VUNNEL_DATA/$provider/metadata.json")): $*")
}

# the CVEs grype-quality-golang's stdlib 1.16.9 matches only by CPE: three the corpus labels tp,
# one it labels fp, two it doesn't label
GO_STDLIB=(CVE-2020-29509 CVE-2020-29511 CVE-2021-29923 CVE-2021-44716 CVE-2022-1705 CVE-2022-1962)
# glibc-2.42 CVEs on the secureos grype-test image: two the corpus labels fp, six the recorded
# proposals are about, one nobody researched. secureos lists each as not affected (fixed "0").
GLIBC=(CVE-2010-4756 CVE-2019-1010022 CVE-2025-15281 CVE-2026-0861 CVE-2026-0915 CVE-2026-18374 CVE-2026-19499 CVE-2026-89092 CVE-2026-95818)
# two unlabeled glibc rows for the gate stable shares with the secureos image
GLIBC_SHARED=(CVE-2025-15281 CVE-2026-95818)
# ubuntu 18.10 and alpine 3.2 CVEs the corpus labels tp; alpine 3.2 matches by CPE only
UBUNTU=(ubuntu:18.10/CVE-2016-2781 ubuntu:18.10/CVE-2018-20482 ubuntu:18.10/CVE-2019-9169)
ALPINE_NVD=(CVE-2016-9840 CVE-2016-9841 CVE-2018-0732)

# every scenario carries the EPSS records for its CVEs: grype v0.100.0's `db search` fails on a DB
# with no EPSS data at all, and yardstick's reasons come from that search
rm -rf "$out"/*/vunnel

extract go-stdlib nvd "${GO_STDLIB[@]}"
extract go-stdlib epss "${GO_STDLIB[@]}"

extract secureos-glibc nvd "${GLIBC[@]}"
extract secureos-glibc secureos "${GLIBC[@]/#/secureos:rolling/}"
extract secureos-glibc epss "${GLIBC[@]}"

extract stable ubuntu "${UBUNTU[@]}"
extract stable nvd "${ALPINE_NVD[@]}" "${GLIBC_SHARED[@]}"
extract stable secureos "${GLIBC_SHARED[@]/#/secureos:rolling/}"
extract stable epss "${UBUNTU[@]#*/}" "${ALPINE_NVD[@]}" "${GLIBC_SHARED[@]}"

{
	echo "Generated by generate.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
	echo "grype $GRYPE_TAG internal/dbtest/cmd/manager extract, from the vunnel workspaces in ${VUNNEL_DATA/#$HOME/~}"
	echo "per scenario and provider (provider metadata.json timestamp): selects"
	printf '%s\n' "${provenance[@]}"
} >"$out/PROVENANCE"
