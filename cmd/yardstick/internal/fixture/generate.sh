#!/usr/bin/env bash
# Regenerates yardstick's test fixtures from the real tools: builds each image under images/,
# catalogs it with a pinned syft (syft-json, CycloneDX, SPDX), and scans each SBOM with two
# pinned grype versions on one pinned DB. Nothing under testdata/ is written by hand; this script
# is the only way to change it. Run it with `go run -C .make . fixtures`.
set -euo pipefail

SYFT_VERSION=v1.54.1
GRYPE_VERSIONS=(v0.119.0 v0.120.1)
# a published DB, from `grype db list` on 2026-10-14
DB_URL=https://grype.anchore.io/databases/v6/vulnerability-db_v6.1.10_2026-10-14T00:28:57Z_1791959434.tar.zst
DB_CHECKSUM=sha256:30d8bcd3c09e03c9f734c522e104c1387e285e3f6e33da2ee7b55f521daadb3f

here=$(cd "$(dirname "$0")" && pwd)
out=$here/testdata
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

os=$(uname -s | tr '[:upper:]' '[:lower:]')
arch=$(uname -m)
case $arch in x86_64) arch=amd64 ;; aarch64) arch=arm64 ;; esac

fetch() { # tool version
	curl -sSfL "https://github.com/anchore/$1/releases/download/$2/$1_${2#v}_${os}_${arch}.tar.gz" | tar -xz -C "$work" "$1"
	mv "$work/$1" "$work/$1-$2"
}

fetch syft "$SYFT_VERSION"
for v in "${GRYPE_VERSIONS[@]}"; do fetch grype "$v"; done

export SYFT_CHECK_FOR_APP_UPDATE=false GRYPE_CHECK_FOR_APP_UPDATE=false
export GRYPE_DB_AUTO_UPDATE=false GRYPE_DB_VALIDATE_AGE=false GRYPE_DB_CACHE_DIR=$work/db
"$work/grype-v0.120.1" db import "$DB_URL?checksum=$DB_CHECKSUM" >/dev/null

rm -rf "$out/sbom" "$out/grype"
mkdir -p "$out/sbom"
for dir in "$here"/images/*/; do
	name=$(basename "$dir")
	echo "fixture image $name" >&2
	docker build -q -t "yardstick-fixture-$name:latest" "$dir" >/dev/null
	"$work/syft-$SYFT_VERSION" "docker:yardstick-fixture-$name:latest" -q \
		-o "syft-json=$out/sbom/$name.syft.json" \
		-o "cyclonedx-json=$out/sbom/$name.cdx.json" \
		-o "spdx-json=$out/sbom/$name.spdx.json"
	for v in "${GRYPE_VERSIONS[@]}"; do
		mkdir -p "$out/grype/$v"
		"$work/grype-$v" "sbom:$out/sbom/$name.syft.json" -o json -q >"$out/grype/$v/$name.json"
	done
done

{
	echo "Generated by generate.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ), $os/$arch."
	echo "syft $SYFT_VERSION: sbom/<image>.{syft,cdx,spdx}.json from docker:yardstick-fixture-<image>:latest"
	for v in "${GRYPE_VERSIONS[@]}"; do echo "grype $v: grype/$v/<image>.json from sbom:<image>.syft.json"; done
	echo "grype DB: $DB_URL ($DB_CHECKSUM)"
	echo "images: built from images/<image>/Dockerfile, base images pinned by digest there"
} >"$out/PROVENANCE"
