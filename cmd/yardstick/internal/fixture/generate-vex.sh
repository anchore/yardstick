#!/usr/bin/env bash
# Regenerates the vendor statement fixtures: an OpenVEX document made by vexctl, OSV records as
# api.osv.dev serves them, and the OpenVEX 0.2.0 schema at a pinned commit of openvex/spec.
# Nothing under testdata/vex, testdata/osv or testdata/openvex is written by hand.
set -euo pipefail

OPENVEX_SPEC_COMMIT=61b5f885d0f481f48683c93345e49ef1a6e9fdff
OSV_IDS=(GHSA-67hx-6x53-jw92 PYSEC-2021-108)
# the fixture deb image (images/deb), as a product
IMAGE='pkg:oci/yardstick-fixture-deb@sha256%3A617d48dd2601779266746a9a382bfb9f3fee2744fba698733b320366f41718b0?repository_url=docker.io/anchore/yardstick-fixture-deb'

here=$(cd "$(dirname "$0")" && pwd)
out=$here/testdata
mkdir -p "$out/vex" "$out/osv" "$out/openvex"

# a fixed date, so the document and its id are the same on every run
export SOURCE_DATE_EPOCH=2026-10-14T10:00:00Z
doc=$out/vex/vendor.openvex.json
vexctl create --author "Example Vendor" --file "$doc" \
	--product "$IMAGE" --subcomponents "pkg:deb/debian/zlib1g@1:1.2.13.dfsg-1?arch=arm64&distro=debian-12" \
	--vuln CVE-2023-45853 --status not_affected --justification vulnerable_code_not_present
vexctl add --in-place --document "$doc" \
	--product "pkg:rpm/rocky/openssl-libs@3.5.5-2.el9_8?arch=aarch64&distro=rocky-9.8&epoch=1" \
	--vuln CVE-2024-0727 --status fixed
vexctl add --in-place --document "$doc" \
	--product "$IMAGE" --vuln CVE-2023-4911 --status affected --action-statement "upgrade libc6"
vexctl add --in-place --document "$doc" \
	--product "$IMAGE" --subcomponents "pkg:deb/debian/ncurses-base@6.4-4?arch=all&distro=debian-12" \
	--vuln CVE-2023-50495 --status under_investigation
vexctl add --in-place --document "$doc" \
	--product "https://example.com/products/appliance" --vuln CVE-2023-38545 --status not_affected \
	--justification component_not_present

for id in "${OSV_IDS[@]}"; do
	curl -sSf "https://api.osv.dev/v1/vulns/$id" -o "$out/osv/$id.json"
done

curl -sSf "https://raw.githubusercontent.com/openvex/spec/$OPENVEX_SPEC_COMMIT/openvex_json_schema.json" \
	-o "$out/openvex/openvex_json_schema_0.2.0.json"

{
	echo "Generated by generate-vex.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
	echo "vex/vendor.openvex.json: $(vexctl version 2>&1 | grep GitVersion | tr -s ' '), SOURCE_DATE_EPOCH=$SOURCE_DATE_EPOCH"
	for id in "${OSV_IDS[@]}"; do
		echo "osv/$id.json: https://api.osv.dev/v1/vulns/$id sha256:$(shasum -a 256 "$out/osv/$id.json" | cut -d' ' -f1)"
	done
	echo "openvex/openvex_json_schema_0.2.0.json: openvex/spec@$OPENVEX_SPEC_COMMIT"
} >"$out/PROVENANCE-vex"
