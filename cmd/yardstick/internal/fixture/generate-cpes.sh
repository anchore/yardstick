#!/usr/bin/env bash
# Regenerates the grype output with deltas between setups: the committed rpm SBOM scanned by the
# pinned grype with CPE matching on for rpm and dpkg packages, on generate.sh's DB. Against
# grype/v0.120.1/rpm.json it adds the CPE-only matches a candidate setup with that config reports.
# Nothing under testdata/grype/v0.120.1-cpes is written by hand.
set -euo pipefail

GRYPE_VERSION=v0.120.1
DB_URL=https://grype.anchore.io/databases/v6/vulnerability-db_v6.1.10_2026-10-14T00:28:57Z_1791959434.tar.zst
DB_CHECKSUM=sha256:30d8bcd3c09e03c9f734c522e104c1387e285e3f6e33da2ee7b55f521daadb3f

here=$(cd "$(dirname "$0")" && pwd)
out=$here/testdata
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

os=$(uname -s | tr '[:upper:]' '[:lower:]')
arch=$(uname -m)
case $arch in x86_64) arch=amd64 ;; aarch64) arch=arm64 ;; esac
curl -sSfL "https://github.com/anchore/grype/releases/download/$GRYPE_VERSION/grype_${GRYPE_VERSION#v}_${os}_${arch}.tar.gz" | tar -xz -C "$work" grype

export GRYPE_CHECK_FOR_APP_UPDATE=false GRYPE_DB_AUTO_UPDATE=false GRYPE_DB_VALIDATE_AGE=false GRYPE_DB_CACHE_DIR=$work/db
"$work/grype" db import "$DB_URL?checksum=$DB_CHECKSUM" >/dev/null
printf 'match:\n  dpkg:\n    using-cpes: true\n  rpm:\n    using-cpes: true\n' >"$work/cpes.yaml"

mkdir -p "$out/grype/$GRYPE_VERSION-cpes"
# from inside testdata, so the SBOM path grype records is the same on every machine
(cd "$out" && "$work/grype" -c "$work/cpes.yaml" sbom:sbom/rpm.syft.json -o json -q | jq -c 'del(.descriptor.configuration)') >"$out/grype/$GRYPE_VERSION-cpes/rpm.json"

{
	echo "Generated by generate-cpes.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ), $os/$arch."
	echo "grype $GRYPE_VERSION with match.rpm.using-cpes and match.dpkg.using-cpes: grype/$GRYPE_VERSION-cpes/rpm.json from sbom:sbom/rpm.syft.json, descriptor.configuration dropped"
	echo "grype DB: $DB_URL ($DB_CHECKSUM)"
} >"$out/PROVENANCE-cpes"
