#!/usr/bin/env bash
# Regenerates the oraclelinux sample taken from anchore/vulnerability-match-labels: the SBOM it
# publishes for the image at ghcr.io/anchore/vml-sbom (gzipped), and grype's output over it, whose
# matches are keyed on ELSA advisories naming one CVE or several. Nothing under testdata/vml is
# written by hand.
set -euo pipefail

GRYPE_VERSION=v0.120.1
# the DB generate.sh scans with
DB_URL=https://grype.anchore.io/databases/v6/vulnerability-db_v6.1.10_2026-10-14T00:28:57Z_1791959434.tar.zst
DB_CHECKSUM=sha256:30d8bcd3c09e03c9f734c522e104c1387e285e3f6e33da2ee7b55f521daadb3f
IMAGE=docker.io/oraclelinux@sha256:a06327c0f1d18d753f2a60bb17864c84a850bb6dcbcf5946dd1a8123f6e75495

here=$(cd "$(dirname "$0")" && pwd)
out=$here/testdata/vml
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# the file name: '/' as '+' and ':' as '-', which a Go module may not hold
file=$(echo "${IMAGE//\//+}" | sed 's/:/-/g').syft.json.gz

rm -rf "$out"
mkdir -p "$out/sbom"
name=${IMAGE%@*}
digest=${IMAGE#*@}
(cd "$work" && oras pull "ghcr.io/anchore/vml-sbom/$name:${digest/:/-}" >/dev/null)
gzip -9 -n -c "$work/data.json" >"$out/sbom/$file"

curl -sSfL "https://github.com/anchore/grype/releases/download/$GRYPE_VERSION/grype_${GRYPE_VERSION#v}_$(uname -s | tr '[:upper:]' '[:lower:]')_$(uname -m | sed 's/x86_64/amd64/;s/aarch64/arm64/').tar.gz" | tar -xz -C "$work" grype
export GRYPE_CHECK_FOR_APP_UPDATE=false GRYPE_DB_AUTO_UPDATE=false GRYPE_DB_VALIDATE_AGE=false GRYPE_DB_CACHE_DIR=$work/db
"$work/grype" db import "$DB_URL?checksum=$DB_CHECKSUM" >/dev/null
gunzip -c "$out/sbom/$file" >"$work/oraclelinux.syft.json"
"$work/grype" "sbom:$work/oraclelinux.syft.json" -o json -q | jq 'del(.source.target.path)' >"$out/grype-oraclelinux.json"

{
	echo "Generated by generate-vml.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
	echo "sbom/$file: ghcr.io/anchore/vml-sbom/$name:${digest/:/-} data.json, gzipped"
	echo "grype-oraclelinux.json: grype $GRYPE_VERSION sbom:<sbom/$file, unzipped> -o json, the temp path dropped"
	echo "grype DB: $DB_URL ($DB_CHECKSUM)"
} >"$out/PROVENANCE"
