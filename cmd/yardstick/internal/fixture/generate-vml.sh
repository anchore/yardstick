#!/usr/bin/env bash
# Regenerates the vulnerability-match-labels sample: the labels of a few images at a pinned commit
# of anchore/vulnerability-match-labels, the SBOMs it publishes for them at
# ghcr.io/anchore/vml-sbom (gzipped), and what grype's DB says each advisory id in them names.
# Nothing under testdata/vml is written by hand.
set -euo pipefail

VML_COMMIT=0c2d7263bb864329656bc3db77560685247fdf2c
GRYPE_VERSION=v0.120.1
# the DB generate.sh scans with
DB_URL=https://grype.anchore.io/databases/v6/vulnerability-db_v6.1.10_2026-10-14T00:28:57Z_1791959434.tar.zst
DB_CHECKSUM=sha256:30d8bcd3c09e03c9f734c522e104c1387e285e3f6e33da2ee7b55f521daadb3f
# label directories: unclear (??) labels, plain CVE and GHSA labels, single- and multi-CVE ELSA
# advisories (oraclelinux), and two labelers disagreeing on one key (test_images@7536ee)
IMAGES=(
	cgr.dev+chainguard+wolfi-base@sha256:be3834598c3c4b76ace6a866edcbbe1fa18086f9ee238b57769e4d230cd7d507
	docker.io+alpine@sha256:ddac200f3ebc9902fb8cfcd599f41feb2151f1118929da21bcef57dc276975f9
	docker.io+anchore+test_images@sha256:58637f273108e3e9eb4df4d73f7b6b1da303cbbf64f65e65fb7762482f2de63d
	ghcr.io+chainguard-images+scanner-test@sha256:59bddc101fba0c45d5c093575c6bc5bfee7f0e46ff127e6bb4e5acaaafb525f9
	registry.replicated.com+library+grype-test@sha256:3339bcd874d21fa3ca5bd20636e793c0c33bd71ace3a18a9a3b3d147b91dd000
	docker.io+oraclelinux@sha256:a06327c0f1d18d753f2a60bb17864c84a850bb6dcbcf5946dd1a8123f6e75495
	docker.io+anchore+test_images@sha256:7536ee345532f674ec9e448e3768db4e546c48220ba2b6ec9bc9cfbfb3b7b74a
)
# two files of an image with no published SBOM: one label with no package, one with a package
NO_SBOM=docker.io+cloudbees+cloudbees-core-mm@sha256:4c564f473d38f23da1caa48c4ef53b958ef03d279232007ad3319b1f38584bdb
NO_SBOM_FILES=(00139277-7f32-471a-a8eb-29e187960bae.json 00042412-dee8-4533-bb7c-a0f37737c955.json)
# the image whose grype output holds advisory-keyed matches
ADVISORY_IMAGE=docker.io+oraclelinux@sha256:a06327c0f1d18d753f2a60bb17864c84a850bb6dcbcf5946dd1a8123f6e75495
# an advisory id grype's DB no longer names (Amazon Linux 2 advisories are ALAS2- there now)
EXTRA_IDS=(ALAS-2021-1608)

here=$(cd "$(dirname "$0")" && pwd)
out=$here/testdata/vml
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# a directory name without ':', which a Go module may not hold
safe() { echo "${1//:/-}"; }

git clone -q --filter=blob:none --no-checkout https://github.com/anchore/vulnerability-match-labels "$work/vml"
git -C "$work/vml" sparse-checkout set --no-cone $(printf 'labels/%s/\n' "${IMAGES[@]}" "$NO_SBOM")
git -C "$work/vml" checkout -q "$VML_COMMIT"

rm -rf "$out"
mkdir -p "$out/labels" "$out/sbom"
for img in "${IMAGES[@]}"; do
	cp -R "$work/vml/labels/$img" "$out/labels/$(safe "$img")"
	exact=$(cat "$out/labels/$(safe "$img")"/*.json | jq -r '.image.exact' | head -1)
	name=${exact%@*}
	digest=${exact#*@}
	(cd "$work" && rm -f data.json metadata.json && oras pull "ghcr.io/anchore/vml-sbom/$name:${digest/:/-}" >/dev/null)
	gzip -9 -n -c "$work/data.json" >"$out/sbom/$(safe "$img").syft.json.gz"
done
mkdir -p "$out/labels/$(safe "$NO_SBOM")"
for f in "${NO_SBOM_FILES[@]}"; do cp "$work/vml/labels/$NO_SBOM/$f" "$out/labels/$(safe "$NO_SBOM")/"; done

curl -sSfL "https://github.com/anchore/grype/releases/download/$GRYPE_VERSION/grype_${GRYPE_VERSION#v}_$(uname -s | tr '[:upper:]' '[:lower:]')_$(uname -m | sed 's/x86_64/amd64/;s/aarch64/arm64/').tar.gz" | tar -xz -C "$work" grype
export GRYPE_CHECK_FOR_APP_UPDATE=false GRYPE_DB_AUTO_UPDATE=false GRYPE_DB_VALIDATE_AGE=false GRYPE_DB_CACHE_DIR=$work/db
"$work/grype" db import "$DB_URL?checksum=$DB_CHECKSUM" >/dev/null
ids=$(find "$out/labels" -name '*.json' -exec cat {} + | jq -r '.vulnerability_id' | grep -vE '^(CVE|GHSA)-' | sort -u)
# shellcheck disable=SC2086
"$work/grype" db search vuln $ids "${EXTRA_IDS[@]}" -o json -q >"$out/grype-db-search.json"
# advisory-keyed matches: oraclelinux 6 reports ELSA ids naming one CVE or several
gunzip -c "$out/sbom/$(safe "$ADVISORY_IMAGE").syft.json.gz" >"$work/advisory.syft.json"
"$work/grype" "sbom:$work/advisory.syft.json" -o json -q | jq 'del(.source.target.path)' >"$out/grype-oraclelinux.json"

{
	echo "Generated by generate-vml.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
	echo "labels/: anchore/vulnerability-match-labels@$VML_COMMIT, labels/<image>/ with ':' as '-'"
	echo "sbom/<image>.syft.json.gz: ghcr.io/anchore/vml-sbom/<repository>:sha256-<hex> data.json, gzipped"
	echo "grype-db-search.json: grype $GRYPE_VERSION db search vuln <every non-CVE, non-GHSA id in labels/> ${EXTRA_IDS[*]} -o json"
	echo "grype-oraclelinux.json: grype $GRYPE_VERSION sbom:<sbom/$(safe "$ADVISORY_IMAGE").syft.json.gz, unzipped> -o json, the temp path dropped"
	echo "grype DB: $DB_URL ($DB_CHECKSUM)"
} >"$out/PROVENANCE"
